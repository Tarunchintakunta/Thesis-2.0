"""Pilot rule: the campaign N comes from the pilot's variance (master prompt 5, step 2).

    python analysis/pilot_size.py --run data/runs/live/pilot --out results/live

Rule (fixed before the pilot, docs/ANALYSIS_PLAN.md):
  duplicate rate   smallest n whose Wilson 95 % interval at the pilot rate is at most
                   +-1 pp (the conservative column uses the end of the pilot's own
                   interval that is closest to 0.5)
  capacity,        n = (1.96 * sd / (5 % of the mean))^2 with the pilot sd (the
  latency          conservative column uses the upper 95 % bound of that sd)
  N                the largest required n over paths and metrics; if it is at most the
                   provisional 1000 the pilot supports N = 1000, otherwise N rises to
                   the required n, capped by the invocation budget
Writes pilot_sizing.csv, pilot_choice.json and pilot_report.md.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import pandas as pd
import yaml
from scipy import stats as st

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from analysis import metrics, stats  # noqa: E402
from analysis.tables import SIGN, md_table, source_label  # noqa: E402


def n_for_wilson(p_hat: float, half_width: float, alpha: float = 0.05, n_max: int = 10_000_000) -> int:
    def half(n: int) -> float:
        _, lo, hi = stats.wilson(p_hat * n, n, alpha)
        return (hi - lo) / 2

    if half(n_max) > half_width:
        return n_max
    lo, hi = 1, n_max
    while lo < hi:
        mid = (lo + hi) // 2
        if half(mid) <= half_width:
            hi = mid
        else:
            lo = mid + 1
    return lo


def sd_upper(sd: float, n: int, alpha: float = 0.05) -> float:
    return sd * math.sqrt((n - 1) / st.chi2.ppf(alpha / 2, n - 1)) if n > 1 else float("nan")


def sizing_table(req: pd.DataFrame, cfg: dict, alpha: float = 0.05) -> pd.DataFrame:
    pr = cfg["practical"]
    hw = pr["duplicate_rate_pp"] / 100
    rows = []
    for path, g in req.groupby("path"):
        retries, dups = int(g["injected_retries"].sum()), int(g["dup_mutations"].sum())
        if retries:
            p, lo, hi = stats.wilson(dups, retries, alpha)
            p_cons = lo if lo > 0.5 else hi if hi < 0.5 else 0.5
            rows.append({"path": path, "metric": "duplicate rate", "pilot_n": retries, "mean": p,
                         "sd": math.sqrt(p * (1 - p)), "target": f"+-{pr['duplicate_rate_pp']} pp",
                         "required_n": n_for_wilson(p, hw, alpha),
                         "conservative_n": stats.n_for_proportion(p_cons, hw, alpha)})
        for metric, col, pct in (("capacity", "capacity_total", pr["capacity_pct"]),
                                 ("latency", "latency_ms", pr["latency_pct"])):
            x = g[col].dropna().astype(float)
            if len(x) < 2:
                continue
            m, sd = float(x.mean()), float(x.std(ddof=1))
            rows.append({"path": path, "metric": metric, "pilot_n": len(x), "mean": m, "sd": sd,
                         "target": f"+-{pct} % of mean", "required_n": stats.n_for_mean(sd, m, pct, alpha),
                         "conservative_n": stats.n_for_mean(sd_upper(sd, len(x), alpha), m, pct, alpha)})
    return pd.DataFrame(rows)


def budget_max_n(cfg: dict, workers_allowance: int = 64) -> int:
    per_n = len(cfg["paths"]) * sum(cfg["multiplicities"])
    sens = cfg["campaign"]["sensitivity_requests_per_cell"] * sum(m for m in cfg["multiplicities"] if m > 1)
    warm = 2 * workers_allowance * cfg.get("warmup_rounds", 0)  # campaign + sensitivity warm-ups
    return int((cfg["budget"]["max_invocations"] - sens - warm) // per_n)


def choose_n(sizing: pd.DataFrame, cfg: dict) -> dict:
    prov = cfg["campaign"]["provisional_requests_per_cell"]
    need = int(sizing["required_n"].max())
    top = sizing.loc[sizing["required_n"].idxmax()]
    cap = budget_max_n(cfg)
    if need <= prov:
        n, why = prov, f"the pilot supports the provisional N (largest requirement {need} <= {prov})"
    elif need <= cap:
        n, why = need, f"the pilot variance needs more than the provisional {prov}"
    else:
        n, why = cap, f"capped by the invocation budget ({cap}); campaign CIs will be wider than the target"
    return {"N": int(n), "required": need, "binding": f"{top['path']} {top['metric']}", "provisional": prov,
            "budget_max_n": cap, "reason": why}


def write_report(sizing: pd.DataFrame, choice: dict, info: dict, cfg: dict, out: str | Path) -> Path:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    pr = cfg["practical"]
    lines = [
        "# Pilot report - campaign replication", "",
        "Generated by `analysis/pilot_size.py`.", "",
        f"- Source: **{source_label(info.get('backend'))}**",
        f"- Pilot run: {info.get('t_start_utc', '?')}, {info.get('requests', '?')} requests, "
        f"{info.get('invocations', '?')} invocations, multiplicity {cfg['pilot']['multiplicity']}", "",
        "## Rule (fixed before the pilot)", "",
        f"- duplicate-mutation rate: 95 % Wilson interval no wider than +-{pr['duplicate_rate_pp']} pp",
        f"- capacity per request: 95 % CI half-width at most {pr['capacity_pct']} % of the mean",
        f"- final-delivery latency: 95 % CI half-width at most {pr['latency_pct']} % of the mean",
        f"- N = largest requirement; at least the provisional {choice['provisional']}; at most "
        f"{choice['budget_max_n']} (invocation budget {cfg['budget']['max_invocations']})", "",
        "## Pilot estimates and required N", "",
        md_table(sizing), "",
        "`conservative_n` uses the pessimistic end of the pilot's own 95 % interval - shown for "
        "transparency, not used for the decision.", "",
        "## Decision", "",
        f"**N = {choice['N']} requests per path per multiplicity** - {choice['reason']}. "
        f"Binding requirement: {choice['binding']} ({choice['required']}).", "",
        "The replication comes from measured pilot variance rather than a fixed guess because "
        "Wen et al. (2025) report large performance variance between serverless runs.", "",
        f"Next: `python -m driver.run --phase campaign --n {choice['N']} --workers 16 --out data/runs/live/campaign`",
        "", SIGN, ""]
    path = out / "pilot_report.md"
    path.write_text("\n".join(lines))
    return path


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", required=True, help="pilot run folder")
    ap.add_argument("--out", required=True)
    ap.add_argument("--config", default=str(ROOT / "config/experiment.yaml"))
    args = ap.parse_args(argv)
    cfg = yaml.safe_load(open(args.config))
    gt, dl, st_, info = metrics.load_run(args.run)
    sizing = sizing_table(metrics.per_request(gt, dl, st_), cfg, cfg["alpha"])
    choice = choose_n(sizing, cfg)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    sizing.to_csv(out / "pilot_sizing.csv", index=False)
    (out / "pilot_choice.json").write_text(json.dumps({**choice, "source": info.get("backend")}, indent=2) + "\n")
    print(write_report(sizing, choice, info, cfg, out), "->", f"N = {choice['N']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
